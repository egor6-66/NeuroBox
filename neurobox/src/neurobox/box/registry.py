"""Наши собственные MCP-серверы — то, чем агент говорит с боксом.

Всё, что нам нужно ОТ агента, приходит инструментами: он общается ими, и заводить рядом второй
способ значило бы, что половина его сообщений живёт мимо общего канала.

Серверов будет несколько, и каждый — свой адрес со своей темой, а не одна свалка ручек. Тогда
рецепт даёт агенту ровно те, что нужны задаче: набор инструментов — это граница, и чем он
точнее, тем меньше агент отвлекается на лишнее.

> [!NOTE]
> Наши серверы НЕ привилегированные. Они попадают в каталог обычными семенами нижнего слоя,
> рецепт решает, давать их агенту или нет, и любой слой выше может их перекрыть. Иначе у нас
> появился бы второй, тайный способ раздавать агенту возможности — и модель поехала бы.
"""

from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

from mcp.server.mcpserver import MCPServer

from neurobox.box import notes


@dataclass(frozen=True)
class Own:
    """Один наш сервер: как зовётся снаружи и что собой представляет."""

    name: str
    """Имя семени в каталоге. По нему рецепт его и называет."""

    description: str
    build: Callable[[], MCPServer]

    @property
    def path(self) -> str:
        """Путь, по которому сервер смонтирован в приложении."""
        return f"/box/{self.name}"


OWN: tuple[Own, ...] = (
    Own(
        # Имя ЛАТИНИЦЕЙ обязательно: из него склеивается имя инструмента у агента
        # (`mcp__notes__note_friction`), и кириллическое туда не проходит — сервер молча
        # оказывается невидимым, а причину видно только если спросить агента, что он видит.
        name="notes",
        description="Ручка, которой агент рассказывает, что мешало работе",
        build=notes.build,
    ),
)
"""Добавить сервер = один модуль рядом и одна запись здесь. Больше нигде ничего."""


def by_name(name: str) -> Own | None:
    return next((own for own in OWN if own.name == name), None)


def connection(seed_name: str, session_id: str | None = None) -> dict[str, Any]:
    """Как подключиться к нашему серверу.

    Адрес известен только здесь: он зависит от того, откуда до нас достучатся, и в файле его
    записать нельзя. Одна функция на всех потребителей — опрос и развёртка обязаны ходить по
    одному адресу, иначе список ручек в пульте окажется не тем, что получит агент.

    Сессия уезжает заголовком и только когда она есть: при опросе её нет, и подставлять пустую
    значило бы записывать заметки в никуда.
    """
    from neurobox.box.session import HEADER
    from neurobox.core.config import settings

    own = by_name(seed_name)
    if own is None:
        return {}

    entry: dict[str, Any] = {
        "type": "http",
        "url": f"{settings.box_url.rstrip('/')}{own.path}/mcp",
    }
    if session_id:
        entry["headers"] = {HEADER.decode(): session_id}
    return entry
