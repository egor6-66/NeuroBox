"""Первый наш MCP-сервер: отзывы о САМОМ БОКСЕ — и о плохом, и о хорошем.

Зачем инструментом, а не разбором ответа: агент общается инструментами, и всё, что нам от него
нужно, должно приходить тем же способом. Разбор текста держался бы на том, что агент не забудет
формат, а забытый формат — это молча потерянная заметка.

Общий петтерн: ручки для работы и рядом ручки для отзывов, у каждого поставщика свои. Отзыв
уходит туда, где лежит ПРИЧИНА, а не туда, где её заметили: недовольство цветами скина — беда
того, кто не дал примеров сочетаний, а не наша, даже если человек сказал об этом нам. Наша
ручка — про наши же ручки, модель под роль, рецепт и сайдкар.

Знак отзыва — оба. Хорошее записывается наравне с плохим: по одним затыкам не видно, что
работает, и разбор превращается в список жалоб. Похвала говорит, что трогать НЕ надо.

Сессию агент не называет: она приходит заголовком, который подставила развёртка. Спрашивать у
агента, где он находится, значило бы доверять его догадке о собственном контексте.
"""

import logging
from typing import Annotated, Literal

from mcp.server.mcpserver import MCPServer
from pydantic import Field
from sqlalchemy.exc import SQLAlchemyError

from neurobox.box.session import current
from neurobox.db.engine import sessions
from neurobox.db.models import Note, NoteKind

log = logging.getLogger("neurobox.box")

INSTRUCTIONS = """
Здесь отзывы о САМОМ БОКСЕ, обоих знаков.

Сюда: рецепт не дал нужной ручки, не хватило разрешений, бокс повёл себя не так, как обещал,
модель не тянет эту роль. И то же самое с плюсом — если работа пошла легко именно из-за того,
как устроен бокс, это тоже отзыв, и он нужен не меньше.

НЕ сюда: всё, чья причина лежит у другого сервера. Даже если человек пожаловался тебе — смотри,
где причина. Не понравились цвета, потому что сервер не дал примеров сочетаний, — это его беда,
и отзыв идёт в его ручку отзывов, а не в нашу.

Свой затык записывай сразу, как упёрся, и работай дальше — разрешения на это не спрашивают.
Обошёл — тем более запиши: обход и есть то, что чинят.

Отзыв СО СЛОВ ЧЕЛОВЕКА — только с его согласия, и его словами, а не пересказом.

Не пиши сюда результаты предметной работы (не сошлась проверка, не нашёлся компонент) — это
нормальные исходы, а не отзывы.
""".strip()


def build() -> MCPServer:
    server = MCPServer(name="neurobox-notes", instructions=INSTRUCTIONS)

    @server.tool(
        name="note_feedback",
        title="Оставить отзыв о боксе",
        description=(
            "Отзыв о САМОМ БОКСЕ, обоих знаков: помешало (рецепт не дал ручки, не хватило "
            "разрешений, модель не тянет роль) или, наоборот, вышло хорошо именно из-за того, "
            "как бокс устроен. Причина у другого сервера — в его ручку отзывов, не сюда."
        ),
    )
    async def note_feedback(
        kind: Annotated[
            Literal["friction", "praise"],
            Field(description="friction — помешало; praise — вышло хорошо"),
        ],
        what: Annotated[
            str,
            Field(
                description=(
                    "Что именно, своими словами. Если это отзыв со слов человека — его "
                    "словами, а не пересказом"
                )
            ),
        ],
        where: Annotated[
            str | None, Field(description="Где именно: имя ручки или сервера, если применимо")
        ] = None,
        workaround: Annotated[
            str | None, Field(description="Чем пришлось обойтись, если обошёл. Для похвалы — пусто")
        ] = None,
    ) -> str:
        session_id = current.get()
        if not session_id:
            # Заголовка нет — значит сервер позвали мимо развёртки. Записывать некуда, и
            # молчаливое согласие оставило бы агента в уверенности, что заметка сохранена.
            return "Отзыв не сохранён: неизвестно, к какому разговору его отнести."

        try:
            async with sessions()() as db:
                db.add(
                    Note(
                        session_id=session_id,
                        kind=NoteKind(kind),
                        what=what.strip(),
                        where=(where or "").strip() or None,
                        workaround=(workaround or "").strip() or None,
                    )
                )
                await db.commit()
        except SQLAlchemyError as error:
            # Причина уходит человеку в логи, а агенту — честный ответ: он должен знать, что
            # отзыв не дошёл, иначе решит, что уже сообщено.
            log.exception("заметка не сохранена", extra={"session": session_id})
            return f"Отзыв не сохранён: {type(error).__name__}. Продолжай работу."

        log.info("отзыв записан", extra={"session": session_id, "kind": kind, "where": where})
        return "Записано. Продолжай работу."

    return server
