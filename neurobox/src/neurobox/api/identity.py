"""Кто пришёл.

Один шов на все ручки. Он проверяет общий токен из окружения и берёт владельца из заголовка
логина — запрос без любого из двух отбивается. Завтра то же место спросит внешний модуль
авторизации, и поменяется только эта функция.

Своей таблицы пользователей и паролей у нас нет и не будет: их всё равно придётся выкинуть,
когда придёт общий модуль, а до тех пор они создавали бы иллюзию настоящего входа.

Логин — ОПОЗНАНИЕ, а не вход: его называет пришедший, и проверить нечем. Это честная цена до
модуля авторизации, и она названа, а не спрятана. Круг тех, кто вообще может назваться,
ограничен токеном: витрина и пульт свои, чужой без токена не назовётся никем.

Токен и логин ездят ТОЛЬКО заголовками. Куки не годятся: браузер не разделяет их по портам, а
сервис живёт на машине по соседству с другим продуктом — кука утекала бы ему на каждом запросе.

Что общий токен НЕ решает, и делать вид не надо: он один на всех, и отозвать его у одного
нельзя. Для своих точек входа это честная цена; для команды чужих нужен модуль.
"""

import logging
import secrets
from typing import Annotated

from fastapi import Depends, Header, HTTPException, status

from neurobox.core.config import settings

log = logging.getLogger("neurobox.identity")

OPEN_PATHS = ("/health", "/ready")
"""Ручки состояния спрашивают «жив ли ты», а не «дай данные». Закрывать их значило бы, что
оркестратор снаружи не может узнать о сервисе даже того, что он поднялся."""


class Who:
    """Кто выполняет запрос."""

    def __init__(self, owner_id: str) -> None:
        self.owner_id = owner_id


def check() -> None:
    """Проверить настройки при старте.

    Отсутствие токена вне разработки — остановка, а не предупреждение: иначе сервис однажды
    поднимется открытым, и никто этого не заметит, пока не станет поздно.
    """
    if settings.environment == "local":
        return

    if not settings.access_token:
        raise RuntimeError(
            "ACCESS_TOKEN не задан. Вне разработки сервис не поднимается без него: "
            "иначе он окажется открыт всем, кто узнает адрес."
        )


LOGIN_HEADER = "X-User-Login"
"""Чьим именем выполняется запрос. Владелец сессий — ровно это значение.
Только латиница и знаки: значение ездит в заголовке HTTP, туда кириллица не проходит."""


def who(
    authorization: Annotated[str | None, Header()] = None,
    x_user_login: Annotated[str | None, Header()] = None,
) -> Who:
    """Опознать пришедшего.

    Только заголовки, и это решение, а не упущение. Куку сервис не принимает: браузер не делит
    куки по портам, а на машине рядом живёт другой продукт на другом порту того же адреса — кука
    уезжала бы ему с каждым запросом. Пульт поэтому и не заводит кук вовсе, а поток событий читает
    обычным запросом, которому заголовок задать можно.

    Токен отвечает «можно ли сюда вообще», логин — «чьим именем». Запрос без логина отбивается
    так же, как без токена: сессии живут по владельцам, и безымянный запрос пришлось бы
    приписывать кому-то выдуманному.
    """
    login = (x_user_login or "").strip()

    if settings.environment == "local" and not settings.access_token:
        # В разработке без токена вход открыт намеренно: поднять сервис у себя должно быть
        # можно одной командой. Названный логин при этом уважается — витрина проверяется
        # локально тем же способом, что и в бою. Вне разработки путь недостижим: `check()`
        # не пустит.
        return Who(login or settings.owner_id)

    token = ""
    if authorization and authorization.lower().startswith("bearer "):
        token = authorization[7:].strip()

    # Сравнение постоянного времени: обычное «==» на строках сравнивает посимвольно и
    # выдаёт длину общего начала задержкой ответа.
    if not token or not secrets.compare_digest(token, settings.access_token):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="нужен токен доступа",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not login:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"нужен логин: заголовок {LOGIN_HEADER}",
        )

    # Предел владельца в базе — 64 знака. Отбить словами лучше, чем уронить запрос на записи.
    if len(login) > 64:
        raise HTTPException(status_code=422, detail="логин длиннее 64 знаков")

    return Who(login)


Caller = Annotated[Who, Depends(who)]
