"""Настройки сервиса — только то, что кто-то действительно читает.

Поле, которое никто не читает, хуже отсутствующего: снаружи оно выглядит рабочей ручкой,
а на деле ни на что не влияет. Настройка заводится вместе с кодом, который её использует.
"""

from pathlib import Path
from typing import Literal

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    project_name: str = "NeuroBox"
    environment: Literal["local", "staging", "production"] = "local"

    config_dir: Path = Path("/config")
    """Файловый слой — то, что человек правит и коммитит. В образ монтируется снаружи."""

    image_config_dir: Path = Path("/opt/neurobox/defaults")
    """Слой образа — запечённые эталоны. Директории может не быть: это пустой слой, не ошибка."""

    database_url: str = "postgresql+asyncpg://neurobox:neurobox@db:5432/neurobox"
    """Адрес базы. Значение по умолчанию — имена из compose: на чистом клоне работает без правки."""

    box_hosts: str = "api:8000,127.0.0.1:8000,localhost:8000"
    """Имена, под которыми к НАШИМ MCP-серверам разрешено обращаться.

    Протокол требует проверять заголовок `Host` — это защита от атаки через подмену DNS, и без
    списка сервер отвечает 421 на всё, кроме петли. Агент живёт в своём контейнере и приходит
    по имени сервиса, поэтому имя обязано быть здесь; список открытый, чтобы добавить своё
    можно было настройкой, а не правкой кода.
    """

    box_url: str = "http://api:8000"
    """Адрес, по которому АГЕНТ достучится до нас. Не localhost: агент живёт в своём
    контейнере, и localhost для него — он сам."""

    access_token: str = ""
    """Общий токен доступа. Только латиница и знаки: он ездит в заголовке HTTP, а туда
    кириллица не проходит вовсе. Вне разработки без него сервис не поднимается: иначе он окажется
    открыт всем, кто узнает адрес. В разработке пустой — поднять сервис у себя должно быть
    можно одной командой."""

    cors_origins: str = ""
    """Источники, которым браузер разрешает ходить к ручкам с чужой страницы, через запятую:
    `http://localhost:5174,http://127.0.0.1:5174`. Пусто — никому: свои потребители (пульт)
    отдаются с того же источника, и им это не нужно. Нужно тому, кто разрабатывает витрину у
    себя на машине против боевого бокса. Точные источники, не `*`: с токеном в заголовке
    открытый список означал бы, что любая страница в интернете может ходить сюда именем того,
    у кого токен в руках."""

    @property
    def cors_origin_list(self) -> list[str]:
        return [o.strip() for o in self.cors_origins.split(",") if o.strip()]

    owner_id: str = "local"
    """Владелец по умолчанию — ТОЛЬКО для разработки без токена, когда логин не назван.
    В бою владелец всегда берётся из заголовка логина; поле существует с первого дня намеренно:
    приписать владельца живым сессиям потом значило бы выбирать, кому они принадлежат."""


settings = Settings()
