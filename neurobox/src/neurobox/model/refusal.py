"""Отказ — значение с именем, а не исключение.

Недопустимое состояние здесь нормальный ход событий: токена нет, файл не разобрался, семя
незнакомо. Пульт обязан объяснить это человеку, а не поймать исключение и показать трассу.
Поэтому отказ возвращается значением: `name` для машины, `means` для человека.
"""

from enum import StrEnum

from pydantic import BaseModel


class RefusalName(StrEnum):
    """Перечень отказов файлового слоя. Пополняется вместе с кодом, который их возвращает."""

    ENV_MISSING = "env-missing"
    """Ссылка `${VAR}` не нашла переменную окружения."""

    UNREADABLE = "unreadable"
    """Файл не разобрался: сломанный YAML, сломанный JSON, не та форма."""

    NAME_TAKEN = "name-taken"
    """Два элемента одного вида с одним именем внутри ОДНОГО слоя."""

    SEED_UNKNOWN = "seed-unknown"
    """Рецепт ссылается на семя, которого нет ни в одном слое."""


class Refusal(BaseModel):
    name: RefusalName
    means: str
    """Человеческое объяснение: что именно и где. Читается в пульте как есть."""

    where: str | None = None
    """Путь файла или имя элемента, если применимо."""
