"""Отказ — значение с именем, а не исключение.

Недопустимое состояние здесь нормальный ход событий: токена нет, файл не разобрался, семя
незнакомо. Пульт обязан объяснить это человеку, а не поймать исключение и показать трассу.
Поэтому отказ возвращается значением: `name` для машины, `means` для человека.
"""

from enum import StrEnum

from pydantic import BaseModel


class RefusalName(StrEnum):
    """Перечень отказов. Пополняется вместе с кодом, который их возвращает, не заранее."""

    ENV_MISSING = "env-missing"
    """Ссылка `${VAR}` не нашла переменную окружения."""

    UNREADABLE = "unreadable"
    """Файл не разобрался: сломанный YAML, сломанный JSON, не та форма."""

    NAME_TAKEN = "name-taken"
    """Два элемента одного вида с одним именем внутри ОДНОГО слоя."""

    SEED_UNKNOWN = "seed-unknown"
    """Рецепт ссылается на семя, которого нет ни в одном слое."""

    TRANSPORT_UNSUPPORTED = "transport-unsupported"
    """Семя объявлено не по http. Рантайм говорит только по http — stdio поднимает сайдкар."""

    SERVER_SILENT = "server-silent"
    """Сервер не ответил на опрос: лежит, недоступен по сети или отверг наши заголовки."""

    NOT_PROBED = "not-probed"
    """Сервер ещё не опрашивался — неизвестно, отвечает ли он и что даёт."""

    AGENT_SILENT = "agent-silent"
    """Агент не ответил: лежит, недоступен по сети или отверг наши заголовки."""

    AGENT_REFUSED = "agent-refused"
    """Агент ответил ошибкой протокола — задачу он не принял."""

    RUN_FAILED = "run-failed"
    """Агент принял задачу и завершил её отказом. Причину он положил в текст ответа."""

    AGENT_UNKNOWN = "agent-unknown"
    """Сессия ссылается на агента, которого нет в каталоге."""

    CANCELED = "canceled"
    """Прогон прерван человеком. Не отказ агента и не сбой — решение."""

    INTERRUPTED = "interrupted"
    """Прогон оборван рестартом сервиса. Продолжить его некому."""


class Refusal(BaseModel):
    name: RefusalName
    means: str
    """Человеческое объяснение: что именно и где. Читается в пульте как есть."""

    where: str | None = None
    """Путь файла или имя элемента, если применимо."""
